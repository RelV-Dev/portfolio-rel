// Run with NODE_PATH pointing to a Playwright installation and a local PHP server.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/rest/v1/public_testimonials*',r=>r.fulfill({json:[{id:1,customer_name:'<img src=x onerror="window.injected=true">',project_title:'Project "quoted"',category:'Web Development',project_proof:null,project_link:'javascript:alert(1)',demo_video_url:null}]}));
 await page.route('**/rest/v1/guestbook*',r=>r.fulfill({json:[{id:'1',name:'Test visitor',message:'Pesan contoh untuk pengujian browser.',rating:5,created_at:'2026-11-10T00:00:00Z'}]}));
 await page.goto('http://127.0.0.1:8765/api/index.php',{waitUntil:'networkidle'});
 await page.screenshot({path:'/tmp/portfolio-desktop.png'});
 assert.equal(await page.locator('#preloader').count(),0);
 assert.equal(await page.locator('script[src*="three"]').count(),0,'3D dependencies must be lazy');
 await page.locator('#chatToggleBtn').click();await page.locator('#chatInput').fill('Apa keahlian Farel?');await page.locator('#chatSendBtn').click();
 await page.waitForFunction(()=>document.querySelector('#chatSendBtn').disabled===false);
 assert.match(await page.locator('#chatMessages').innerText(),/belum dikonfigurasi/);
 await page.keyboard.press('Escape');
 await page.locator('.journey-card').first().focus();await page.keyboard.press('Enter');
 assert.equal(await page.locator('#journeyModal').getAttribute('hidden'),null);
 assert.equal(await page.locator('#journeyModal').getAttribute('aria-modal'),'true');
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('.journey-card').first().evaluate(el=>el===document.activeElement),true,'Focus returns to trigger');
 await page.locator('#testimonials').scrollIntoViewIfNeeded();
 await page.locator('.testimonial-view-btn').first().click();
 assert.equal(await page.locator('#lightboxBody img').count(),0,'No private proof or missing images');
 assert.equal(await page.evaluate(()=>window.injected),undefined,'Database text cannot execute');
 assert.equal(await page.locator('#lightboxBody a[href^="javascript:"]').count(),0);
 await page.keyboard.press('Escape');
 await page.locator('#pauseGuestbook').click();assert.equal(await page.locator('#pauseGuestbook').getAttribute('aria-pressed'),'true');
 await page.locator('#openGuestbookModalBtn').click();await page.keyboard.press('Escape');
 assert.equal(await page.locator('#guestbookModalOverlay').evaluate(el=>el.classList.contains('active')),false);
 assert.deepEqual(errors,[]);
 await page.route('https://github-stats-api-tau.vercel.app/**',r=>r.fulfill({json:{username:'RelV-Dev',totalRepos:5,totalCommits:20,contributionsCurrentYear:20,topLanguages:[],contributionGraph:Array.from({length:14},(_,i)=>({date:'2026-11-'+String(i+1).padStart(2,'0'),count:2,level:1}))}}));
 await page.locator('#github-3d-canvas button').click();
 await page.locator('#github-3d-canvas canvas').waitFor({timeout:45000});
 assert.equal(await page.evaluate(()=>typeof THREE.FontLoader),'function');
 assert.equal(await page.evaluate(()=>typeof THREE.TextGeometry),'function');
 assert.deepEqual(errors,[]);
 await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:8765/api/index.php',{waitUntil:'networkidle'});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'No mobile overflow');
 await page.screenshot({path:'/tmp/portfolio-mobile.png'});
 await page.locator('.menu-toggle').click();await page.locator('#primaryNav a').first().click();assert.notEqual(await page.locator('body').evaluate(el=>getComputedStyle(el).overflow),'hidden');
 await page.emulateMedia({reducedMotion:'reduce'});await page.locator('#guestbook').scrollIntoViewIfNeeded();
 const before=await page.locator('#guestbookGrid').evaluate(el=>getComputedStyle(el).transform);await page.waitForTimeout(150);assert.equal(await page.locator('#guestbookGrid').evaluate(el=>getComputedStyle(el).transform),before);
 assert.deepEqual(errors,[]);console.log('PASS desktop/mobile, chat failure, safe rendering, modal keyboard/focus, pause, reduced motion and lazy 3D');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
